// Resolves the 30s preview clip for every song in src/lib/content.ts through the iTunes
// Search API and writes them to src/lib/song-previews.ts, so the site never looks them up at
// runtime: iTunes rate-limits bursts of lookups, which left the play buttons dead.
//
//   node scripts/gen-song-previews.mjs
//
// Re-run it after changing the songs list. A song it can't resolve is simply left out, and
// the page falls back to a live lookup for that one.
import { readFileSync, writeFileSync } from 'node:fs';

const norm = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const src = readFileSync('src/lib/content.ts', 'utf8');
const block = src.match(/export const songs: Song\[\] = \[([\s\S]*?)\n\];/);
if (!block) throw new Error('could not find the songs array in src/lib/content.ts');
const songs = [...block[1].matchAll(/title:\s*'([^']+)',\s*artist:\s*'([^']+)'/g)].map(
	([, title, artist]) => ({ title, artist })
);
if (!songs.length) throw new Error('no songs matched in the songs array');

const found = {};
for (const s of songs) {
	const url = new URL('https://itunes.apple.com/search');
	url.searchParams.set('term', `${s.title} ${s.artist}`);
	url.searchParams.set('media', 'music');
	url.searchParams.set('entity', 'song');
	url.searchParams.set('limit', '10');
	try {
		const res = await fetch(url, { headers: { accept: 'application/json' } });
		if (!res.ok) throw new Error(`iTunes HTTP ${res.status}`);
		// The API sometimes answers with text/javascript, so parse by hand.
		const { results = [] } = JSON.parse(await res.text());
		const playable = results.filter((r) => r.previewUrl);
		// Prefer a hit where both title and artist match; fall back to the first playable one.
		const best =
			playable.find(
				(r) =>
					norm(r.trackName ?? '').includes(norm(s.title)) &&
					norm(r.artistName ?? '').includes(norm(s.artist))
			) ??
			playable.find((r) => norm(r.artistName ?? '').includes(norm(s.artist))) ??
			playable[0];
		if (best?.previewUrl) {
			found[s.title] = best.previewUrl;
			console.log(`ok    ${s.title} — ${best.trackName} / ${best.artistName}`);
		} else {
			console.log(`MISS  ${s.title} / ${s.artist} — no playable hit`);
		}
	} catch (err) {
		console.log(`FAIL  ${s.title} / ${s.artist} — ${err.message}`);
	}
	await sleep(400); // gentle: iTunes rate-limits bursts
}

const body = Object.entries(found)
	.map(([title, clip]) => `\t${JSON.stringify(title)}: ${JSON.stringify(clip)}`)
	.join(',\n');
writeFileSync(
	'src/lib/song-previews.ts',
	'// Generated by scripts/gen-song-previews.mjs — do not edit by hand.\n' +
		'// The 30s preview clips for the songs in content.ts, pinned so the page never has to ask\n' +
		'// iTunes at runtime (it rate-limits bursts, which greys the play buttons out). A song\n' +
		'// missing from here falls back to a live lookup through /api/preview.\n' +
		`export const SONG_PREVIEWS: Record<string, string> = {\n${body}\n};\n`
);
console.log(`\nwrote src/lib/song-previews.ts with ${Object.keys(found).length}/${songs.length} clips`);
