<script lang="ts">
	// Interactive maximum-power-transfer curve. Drag the load resistance and watch
	// the power delivered to the load peak exactly when R_L = R_th, while the
	// efficiency keeps climbing - the trade-off the lecturer spent the lesson on.
	// Defaults are his graph example: V_th = 10 V, R_th = 4 ohm (peak 6.25 W at 4 ohm).
	let { vth = 10, rth = 4 }: { vth?: number; rth?: number } = $props();

	let rl = $state(4); // load resistance, ohms

	const RLMAX = 40;
	const PMAX = (vth * vth) / (4 * rth); // peak load power, at R_L = R_th

	const loadPower = (r: number) => (vth * vth * r) / (rth + r) ** 2;
	const efficiency = (r: number) => r / (r + rth); // 0..1

	let p = $derived(loadPower(rl));
	let eta = $derived(efficiency(rl));
	let totalPower = $derived((vth * vth) / (rth + rl)); // generated by the source

	// plot box
	const x0 = 52;
	const x1 = 340;
	const y0 = 196;
	const y1 = 24;
	const sx = (r: number) => x0 + (r / RLMAX) * (x1 - x0);
	const syP = (pw: number) => y0 - (pw / (PMAX * 1.08)) * (y0 - y1); // power axis
	const syE = (e: number) => y0 - e * (y0 - y1); // efficiency 0..1 on same box

	const sample = (f: (r: number) => number, sy: (v: number) => number) => {
		let d = '';
		for (let i = 0; i <= 80; i++) {
			const r = (i / 80) * RLMAX;
			d += (i === 0 ? 'M' : 'L') + sx(r).toFixed(1) + ' ' + sy(f(r)).toFixed(1) + ' ';
		}
		return d.trim();
	};
	const powerPath = sample(loadPower, syP);
	const effPath = sample(efficiency, syE);

	let markX = $derived(sx(rl));
</script>

<div class="demo">
	<div class="controls">
		<label for="rl">load resistance R&#8343; = <b>{rl.toFixed(1)} &#8486;</b></label>
		<input id="rl" type="range" min="0.2" max={RLMAX} step="0.2" bind:value={rl} />
		<div class="readout">
			<div><span class="p">load power</span> = {vth}&sup2;&middot;R&#8343;/(R&#8348;&#8341;+R&#8343;)&sup2; = <b>{p.toFixed(2)} W</b></div>
			<div><span class="e">efficiency</span> = R&#8343;/(R&#8343;+R&#8348;&#8341;) = <b>{(eta * 100).toFixed(1)}%</b></div>
			<div><span class="t">total generated</span> = <b>{totalPower.toFixed(2)} W</b></div>
		</div>
		<p class="hint">
			power peaks at <b>R&#8343; = R&#8348;&#8341; = {rth} &#8486;</b> ({PMAX.toFixed(2)} W) - and at that exact
			point efficiency is only <b>50%</b>. Drag past it: efficiency keeps climbing but the power you
			actually deliver falls away. You cannot have both.
		</p>
	</div>

	<svg viewBox="0 0 360 230" aria-label="maximum power transfer curve">
		<!-- axes -->
		<line x1={x0} y1={y0} x2={x1} y2={y0} stroke="#201d18" stroke-width="1.5" marker-end="url(#mx)" />
		<line x1={x0} y1={y0} x2={x0} y2={y1} stroke="#201d18" stroke-width="1.5" marker-end="url(#my)" />
		<text x={x1 - 2} y={y0 + 20} font-size="12" fill="#6a645a" text-anchor="end">R&#8343; (&#8486;)</text>
		<text x={x0 - 6} y={y1 + 2} font-size="12" fill="#6a645a" text-anchor="end">P, &eta;</text>
		<!-- match line -->
		<line x1={sx(rth)} y1={y0} x2={sx(rth)} y2={y1} stroke="#9a3b2e" stroke-width="1.2" stroke-dasharray="4 4" opacity="0.6" />
		<text x={sx(rth) + 4} y={y1 + 12} font-size="11" fill="#9a3b2e">R&#8343; = R&#8348;&#8341;</text>
		<!-- curves -->
		<path d={effPath} fill="none" stroke="#5a4a9e" stroke-width="2" stroke-dasharray="6 3" />
		<path d={powerPath} fill="none" stroke="#0e6b63" stroke-width="2.6" />
		<!-- draggable marker -->
		<line x1={markX} y1={y0} x2={markX} y2={y1} stroke="#b5631f" stroke-width="1" opacity="0.4" />
		<circle cx={markX} cy={syP(p)} r="5" fill="#0e6b63" />
		<circle cx={markX} cy={syE(eta)} r="4" fill="#5a4a9e" />
		<!-- legend -->
		<g font-size="11" font-family="Inter, sans-serif">
			<line x1={x0 + 6} y1={y1 + 30} x2={x0 + 26} y2={y1 + 30} stroke="#0e6b63" stroke-width="2.6" />
			<text x={x0 + 30} y={y1 + 34} fill="#0e6b63">load power</text>
			<line x1={x0 + 6} y1={y1 + 48} x2={x0 + 26} y2={y1 + 48} stroke="#5a4a9e" stroke-width="2" stroke-dasharray="6 3" />
			<text x={x0 + 30} y={y1 + 52} fill="#5a4a9e">efficiency</text>
		</g>
		<defs>
			<marker id="mx" markerWidth="9" markerHeight="9" refX="7" refY="4.5" orient="auto"><path d="M0,0 L9,4.5 L0,9 z" fill="#201d18" /></marker>
			<marker id="my" markerWidth="9" markerHeight="9" refX="7" refY="4.5" orient="auto"><path d="M0,0 L9,4.5 L0,9 z" fill="#201d18" /></marker>
		</defs>
	</svg>
</div>

